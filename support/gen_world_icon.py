#!/usr/bin/env python3
"""Draw a globe ("world") launcher icon for the trip companion screen.

Output:
  * src/world_icon.c  - LVGL 9 lv_image_dsc_t + pixel data (B,G,R,A byte order)
  * src/world_icon.h  - extern declaration
  * world_icon_preview.png (next to this script, for visual inspection)

Pure stdlib: the globe (outline, equator, tropics and meridians) is rendered
with 4x supersampling for anti-aliasing, then box-downsampled to 64x64.
"""

import math
import os
import struct
import zlib

SIZE = 64                       # output icon edge in pixels
SS = 4                          # supersampling factor
RADIUS = 0.86                   # globe radius relative to half the icon size
LINE = 0.075                    # line half-width relative to the globe radius
COLOR = (0x5A, 0xC8, 0xFA)      # R, G, B globe line color (light blue)


# ---------------------------------------------------------------------------
# Globe rendering (supersampled) and downsample
# ---------------------------------------------------------------------------

def render():
    n = SIZE * SS
    px = bytearray(n * n * 4)
    for y in range(n):
        for x in range(n):
            # globe-normalized coordinates: unit circle = globe outline
            gx = ((x + 0.5) / n * 2 - 1) / RADIUS
            gy = ((y + 0.5) / n * 2 - 1) / RADIUS
            r = math.hypot(gx, gy)
            lit = abs(r - 1.0) < LINE               # outline
            if r < 1.0:
                if abs(gy) < LINE:                  # equator
                    lit = True
                if abs(gx) < LINE:                  # central meridian
                    lit = True
                if abs(abs(gy) - 0.45) < LINE:      # tropics
                    lit = True
                # side meridians: ellipse through the poles, x radius 0.5;
                # distance approximated as |e - 1| / |grad e|
                e = (gx / 0.5) ** 2 + gy * gy
                grad = 2 * math.hypot(4 * gx, gy)
                if grad > 0 and abs(e - 1.0) / grad < LINE:
                    lit = True
            o = (y * n + x) * 4
            alpha = 255 if lit else 0
            px[o:o + 4] = bytes((COLOR[2], COLOR[1], COLOR[0], alpha))
    return px


def downsample(src):
    n = SIZE * SS
    out = bytearray(SIZE * SIZE * 4)    # B,G,R,A
    for oy in range(SIZE):
        for ox in range(SIZE):
            b = g = r = a = 0
            for sy in range(SS):
                for sx in range(SS):
                    i = ((oy * SS + sy) * n + ox * SS + sx) * 4
                    b += src[i]
                    g += src[i + 1]
                    r += src[i + 2]
                    a += src[i + 3]
            cnt = SS * SS
            o = (oy * SIZE + ox) * 4
            out[o:o + 4] = bytes((b // cnt, g // cnt, r // cnt, a // cnt))
    return out


# ---------------------------------------------------------------------------
# Output writers
# ---------------------------------------------------------------------------

def write_png(path, pixels, size, scale=1):
    """Preview PNG composited over a dark background."""

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    out = size * scale
    raw = bytearray()
    for py in range(out):
        raw.append(0)  # filter: none
        for px in range(out):
            i = ((py // scale) * size + (px // scale)) * 4
            b, g, r, a = pixels[i:i + 4]
            bg = 17
            raw += bytes(((r * a + bg * (255 - a)) // 255,
                          (g * a + bg * (255 - a)) // 255,
                          (b * a + bg * (255 - a)) // 255))

    ihdr = struct.pack(">IIBBBBB", out, out, 8, 2, 0, 0, 0)  # RGB
    png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr)
           + chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + chunk(b"IEND", b""))
    with open(path, "wb") as f:
        f.write(png)


def write_c(path, pixels, size):
    rows = []
    for i in range(0, len(pixels), 16):
        rows.append("    " + ", ".join(f"0x{v:02X}" for v in pixels[i:i + 16]))
    data = ",\n".join(rows)
    content = f"""/**
 * @file      world_icon.c
 * @brief     World (globe) launcher icon, {size}x{size} ARGB8888, for the trip
 *            companion screen. Generated by support/gen_world_icon.py -
 *            do not edit by hand.
 */
#include "world_icon.h"

static const uint8_t world_icon_map[] = {{
{data}
}};

const lv_image_dsc_t world_icon = {{
    .header.magic = LV_IMAGE_HEADER_MAGIC,
    .header.cf = LV_COLOR_FORMAT_ARGB8888,
    .header.flags = 0,
    .header.w = {size},
    .header.h = {size},
    .header.stride = {size} * 4,
    .data_size = sizeof(world_icon_map),
    .data = world_icon_map,
}};
"""
    with open(path, "w", newline="\n") as f:
        f.write(content)


def write_h(path):
    content = """/**
 * @file      world_icon.h
 * @brief     World (globe) launcher icon (see world_icon.c).
 */
#pragma once

#include <lvgl.h>

extern const lv_image_dsc_t world_icon;
"""
    with open(path, "w", newline="\n") as f:
        f.write(content)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    pixels = downsample(render())
    out_src = os.path.normpath(os.path.join(here, "..", "src"))
    write_c(os.path.join(out_src, "world_icon.c"), pixels, SIZE)
    write_h(os.path.join(out_src, "world_icon.h"))
    write_png(os.path.join(here, "world_icon_preview.png"), pixels, SIZE,
              scale=4)
    print(f"icon written ({len(pixels)} bytes of pixel data)")


if __name__ == "__main__":
    main()
